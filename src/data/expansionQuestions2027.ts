/**
 * Authored items written against the official 2027 Level I learning modules
 * (CFA Institute topic outline) to cover modules the original bank did not.
 * Options follow exam conventions: numbers smallest to largest, words
 * shortest to longest, three unique choices, no "all/none of the above".
 */
function q(
  id: number,
  losCode: string,
  stem: string,
  options: [string, string, string],
  correctOption: OptionKey,
  algebraicSolution: string,
  trapCategory: string,
  errorModeDefault: ErrorMode,
  feedback: [string, string, string],
  calculatorKeystrokes = ""
): VignetteQuestion {
  const keys: OptionKey[] = ["A", "B", "C"];
  const distractorAutopsy = Object.fromEntries(
    keys.map((key, index) => [key, key === correctOption ? `Correct. ${feedback[index]}` : feedback[index]])
  ) as Record<OptionKey, string>;
  return {
    id,
    losCode,
    stem,
    options: { A: options[0], B: options[1], C: options[2] },
    correctOption,
    algebraicSolution,
    calculatorKeystrokes: calculatorKeystrokes || "Concept question: no calculator steps required.",
    trapCategory,
    errorModeDefault,
    distractorAutopsy,
  };
}

