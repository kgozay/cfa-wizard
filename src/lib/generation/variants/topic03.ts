import { between, int, money, num, pct } from "../format";
import { numericVariant } from "./dsl";

const ann = (pmt: number, r: number, n: number) => (pmt * (1 - Math.pow(1 + r, -n))) / r;
const npv = (r: number, flows: number[]) => flows.reduce((s, cf, t) => s + cf / Math.pow(1 + r, t), 0);
const solve = (f: (x: number) => number, lo: number, hi: number) => {
  let a = lo;
  let b = hi;
  for (let i = 0; i < 200; i++) {
    const m = (a + b) / 2;
    if (Math.sign(f(m)) === Math.sign(f(a))) a = m;
    else b = m;
  }
  return (a + b) / 2;
};
const irr = (flows: number[]) => solve((r) => npv(r, flows), -0.99, 10);
const bondPrice = (c: number, y: number, n: number) => ann(c, y, n) + 1000 / Math.pow(1 + y, n);

