const ann = (pmt: number, r: number, n: number) => (pmt * (1 - Math.pow(1 + r, -n))) / r;
const price = (coupon: number, y: number, n: number, face = 1000) => ann(coupon, y, n) + face / Math.pow(1 + y, n);
const solve = (f: (x: number) => number, lo: number, hi: number) => {
  let a = lo;
  let b = hi;
  for (let i = 0; i < 200; i++) {
    const m = (a + b) / 2;
    if (Math.sign(f(m)) === Math.sign(f(a))) a = m;
    else b = m;
  }
  return (a + b) / 2;
};
const macaulay = (coupon: number, y: number, n: number, face = 100) => {
  let weighted = 0;
  for (let t = 1; t <= n; t++) weighted += (t * (coupon + (t === n ? face : 0))) / Math.pow(1 + y, t);
  return weighted / price(coupon, y, n, face);
};

